// ECDICT 全量四六级词（约 5800 条），动态加载避免进主包
type EcdictEntry = Omit<VocabWord, 'root' | 'collocation'>

let ecdictCache: VocabWord[] | null = null

export async function loadEcdict(): Promise<VocabWord[]> {
  if (ecdictCache) return ecdictCache
  const data = (await import('./vocab.json')).default as EcdictEntry[]
  ecdictCache = data as VocabWord[]
  return ecdictCache
}

let allCache: VocabWord[] | null = null

export async function getAllVocab(): Promise<VocabWord[]> {
  if (allCache) return allCache
  const ecdict = await loadEcdict()
  const handWords = new Set(VOCAB_BANK.map((w) => w.word.toLowerCase()))
  allCache = [...VOCAB_BANK, ...ecdict.filter((w) => !handWords.has(w.word.toLowerCase()))]
  return allCache
}

/** 四级：cet4 + both；六级：cet6 + both */
export function filterVocabByLevel(words: VocabWord[], level: ExamLevel): VocabWord[] {
  return words.filter((w) => w.level === level || w.level === 'both')
}

export function wordInitial(word: string): string {
  const ch = (word.trim()[0] || '#').toUpperCase()
  return ch >= 'A' && ch <= 'Z' ? ch : '#'
}

/** A–Z 分组，组内按单词排序 */
export function groupVocabByLetter(words: VocabWord[]): { letter: string; words: VocabWord[] }[] {
  const map = new Map<string, VocabWord[]>()
  for (const w of words) {
    const L = wordInitial(w.word)
    const list = map.get(L)
    if (list) list.push(w)
    else map.set(L, [w])
  }
  const letters = 'ABCDEFGHIJKLMNOPQRSTUVWXYZ'.split('')
  if (map.has('#')) letters.push('#')
  return letters
    .filter((L) => map.has(L))
    .map((L) => ({
      letter: L,
      words: (map.get(L) || []).slice().sort((a, b) => a.word.localeCompare(b.word, 'en', { sensitivity: 'base' })),
    }))
}
